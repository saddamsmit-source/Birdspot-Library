"""Generate guide metadata from the reviewed local photo register."""
import json
from pathlib import Path
ROOT=Path(__file__).resolve().parents[2]
data=json.loads((ROOT/'assets/species/credits.json').read_text())
(ROOT/'src/features/species/guidePhotos.js').write_text('/** Generated by tools/species/build.py; reviewed source: assets/species/credits.json. */\nexport const GUIDE_PHOTOS = Object.freeze('+json.dumps(data,ensure_ascii=False,indent=2)+');\n')

media = json.loads((ROOT / 'assets/species/field-guide-media.json').read_text(encoding='utf-8'))
(ROOT / 'src/features/species/guideMedia.js').write_text(
    '/** Generated by tools/species/build.py from assets/species/field-guide-media.json. */\n'
    f'export const GUIDE_AUDIO = Object.freeze({json.dumps(media["audio"], ensure_ascii=False, indent=2)});\n'
    f'export const GUIDE_PLUMAGE = Object.freeze({json.dumps(media["plumage"], ensure_ascii=False, indent=2)});\n',
    encoding='utf-8',
)
